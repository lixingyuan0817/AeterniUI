namespace AeterniUI.Enums;

/// <summary>
/// Surface finish of a <c>FlashCard</c> media area. The sheen is an optical
/// overlay that follows the pointer, imitating the light response of a physical
/// trading card: <see cref="Shine" /> is a metallic white sweep, <see cref="Holo" />
/// adds the rainbow diffraction band of a holographic card.
/// </summary>
public enum FlashCardSheen
{
    None,
    Shine,
    Holo
}
